"""Create a simple plot and save it as an image."""

import matplotlib.pyplot as plt


def main():
    """Save a plot in the current working directory."""
    x = [1, 2, 3, 4, 5]
    y = [2, 4, 3, 5, 6]

    plt.plot(x, y, marker="o")
    plt.title("Plot generated by GitHub Actions")
    plt.xlabel("Example number")
    plt.ylabel("Value")
    plt.tight_layout()
    plt.savefig("plot.png")
    plt.close()
    print("Saved plot.png")


if __name__ == "__main__":
    main()
